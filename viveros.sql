-- 5. EJEMPLOS DE DELETE (y UPDATE) CON SUS EFECTOS EN CASCADA
--    Cada ejemplo va en una transacción que termina en ROLLBACK para
--    que los datos de la sección 4 sigan intactos. Para un borrado
--    permanente, cambiar ROLLBACK por COMMIT. Cada SELECT de
--    comprobación debe devolver 0.

-- 5.1 Borrar una zona: CASCADE elimina su stock (zona_tiene_producto).
BEGIN;
DELETE FROM zona WHERE id_vivero = 1 AND nombre = 'Exterior Norte';
SELECT count(*) FROM zona_tiene_producto WHERE id_vivero = 1 AND nombre_zona = 'Exterior Norte';
ROLLBACK;

-- 5.2 Borrar un cliente: CASCADE elimina sus correos, bonificaciones, pedidos y las líneas de esos pedidos (pedidos 1 y 6).
BEGIN;
DELETE FROM cliente WHERE id = 1;
SELECT count(*) FROM (
    SELECT 1 FROM cliente_correo          WHERE id_cliente = 1
    UNION ALL SELECT 1 FROM cliente_bonificacion    WHERE id_cliente = 1
    UNION ALL SELECT 1 FROM pedido                  WHERE id_cliente = 1
    UNION ALL SELECT 1 FROM pedido_incluye_producto WHERE id_pedido IN (1, 6)
) restos;
ROLLBACK;

-- 5.3 Borrar un producto que solo tiene stock (nunca pedido): se borra y CASCADE elimina su stock.
BEGIN;
DELETE FROM producto WHERE codigo = 'P007';
SELECT count(*) FROM zona_tiene_producto WHERE codigo_producto = 'P007';
ROLLBACK;

-- 5.4 Borrar un empleado que no gestiona ningún pedido: se borra sin problema.
BEGIN;
DELETE FROM empleado WHERE dni = '45678901G' RETURNING dni, nombre;
ROLLBACK;

-- 5.5 Borrados rechazados por RESTRICT (cada uno debe fallar): producto con pedidos, empleado que gestiona pedidos y vivero con empleados.
DO $do$
DECLARE q TEXT;
BEGIN
    FOREACH q IN ARRAY ARRAY[
        $$DELETE FROM producto WHERE codigo = 'P002'$$,
        $$DELETE FROM empleado WHERE dni = '12345678Z'$$,
        $$DELETE FROM vivero   WHERE id = 5$$ ]
    LOOP
        BEGIN
            EXECUTE q;
            RAISE NOTICE 'NO rechazado: %', q;
        EXCEPTION WHEN foreign_key_violation THEN
            RAISE NOTICE 'Rechazado (RESTRICT): %', q;
        END;
    END LOOP;
END $do$;

-- 5.6 Borrar un vivero: tras reasignar a su empleado, el borrado funciona y CASCADE elimina sus zonas y el stock de esas zonas.
BEGIN;
UPDATE empleado SET id_vivero = 4 WHERE dni = '78901234X';
DELETE FROM vivero WHERE id = 5;
SELECT (SELECT count(*) FROM zona                WHERE id_vivero = 5)
     + (SELECT count(*) FROM zona_tiene_producto WHERE id_vivero = 5) AS restos;
ROLLBACK;

-- 5.7 Actualización en cascada (ON UPDATE CASCADE): cambiar el código de un producto se propaga a zona_tiene_producto y pedido_incluye_producto.
BEGIN;
UPDATE producto SET codigo = 'P101' WHERE codigo = 'P001';
SELECT (SELECT count(*) FROM zona_tiene_producto   WHERE codigo_producto = 'P101') AS en_stock,
       (SELECT count(*) FROM pedido_incluye_producto WHERE codigo_producto = 'P101') AS en_pedidos;
ROLLBACK;

