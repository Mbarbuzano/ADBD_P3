-- 2. TABLAS
--    Orden: primero las que no dependen de nadie, luego las que referencian a otras y al final las tablas de las relaciones N:M.

-- VIVERO. "Localización" (compuesto) -> columnas latitud y longitud.
CREATE TABLE vivero (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    latitud   NUMERIC(9,6) NOT NULL,
    longitud  NUMERIC(9,6) NOT NULL,
    CONSTRAINT pk_vivero PRIMARY KEY (id),
    CONSTRAINT ck_vivero_latitud  CHECK (latitud  BETWEEN  -90 AND  90),
    CONSTRAINT ck_vivero_longitud CHECK (longitud BETWEEN -180 AND 180)
);

-- ZONA: entidad DÉBIL de Vivero (relación identificadora "Pertenece").
-- Clave primaria = clave del vivero + identificador parcial (nombre).
-- Si se borra/actualiza el vivero, sus zonas lo siguen (CASCADE).
CREATE TABLE zona (
    id_vivero  INTEGER       NOT NULL,
    nombre     VARCHAR(60)   NOT NULL,
    latitud    NUMERIC(9,6)  NOT NULL,
    longitud   NUMERIC(9,6)  NOT NULL,
    CONSTRAINT pk_zona PRIMARY KEY (id_vivero, nombre),
    CONSTRAINT fk_zona_vivero FOREIGN KEY (id_vivero)
        REFERENCES vivero (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT ck_zona_nombre   CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_zona_latitud  CHECK (latitud  BETWEEN  -90 AND  90),
    CONSTRAINT ck_zona_longitud CHECK (longitud BETWEEN -180 AND 180)
);

-- EMPLEADO. La relación "Asignado" es 1:N, así que su clave foránea
-- (id_vivero) y su atributo compuesto "Puesto" (nombre + periodo inicio/fin) pasan a la tabla del lado N, es decir, Empleado.
-- puesto_fin NULL = puesto vigente.
-- RESTRICT: no se puede borrar un vivero con empleados (hay que reasignarlos).
CREATE TABLE empleado (
    dni            CHAR(9)       NOT NULL,
    nombre         VARCHAR(100)  NOT NULL,
    id_vivero      INTEGER       NOT NULL,
    puesto_nombre  VARCHAR(50)   NOT NULL,
    puesto_inicio  DATE          NOT NULL,
    puesto_fin     DATE,
    CONSTRAINT pk_empleado PRIMARY KEY (dni),
    CONSTRAINT fk_empleado_vivero FOREIGN KEY (id_vivero)
        REFERENCES vivero (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_empleado_dni    CHECK (dni ~ '^[0-9]{8}[A-Z]$'),
    CONSTRAINT ck_empleado_puesto CHECK (puesto_fin IS NULL OR puesto_fin >= puesto_inicio)
);

CREATE TABLE producto (
    codigo  VARCHAR(10)   NOT NULL,
    nombre  VARCHAR(100)  NOT NULL,
    precio  NUMERIC(8,2)  NOT NULL,
    CONSTRAINT pk_producto PRIMARY KEY (codigo),
    CONSTRAINT ck_producto_precio CHECK (precio >= 0)
);

-- CLIENTE. Atributo compuesto "Tajinaste Plus": fecha_ingreso queda como columna (NULL = el cliente no pertenece a Tajinaste Plus).
-- Sus componentes/atributos multivaluados (correo, bonificaciones) van a tablas aparte.
CREATE TABLE cliente (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(100) NOT NULL,
    fecha_ingreso  DATE,
    CONSTRAINT pk_cliente PRIMARY KEY (id),
    CONSTRAINT ck_cliente_nombre CHECK (length(trim(nombre)) > 0)
);

-- Correo: atributo MULTIVALUADO -> tabla propia (clave = cliente + correo).
CREATE TABLE cliente_correo (
    id_cliente  INTEGER       NOT NULL,
    correo      VARCHAR(120)  NOT NULL,
    CONSTRAINT pk_cliente_correo PRIMARY KEY (id_cliente, correo),
    CONSTRAINT uq_cliente_correo UNIQUE (correo),
    CONSTRAINT fk_cliente_correo FOREIGN KEY (id_cliente)
        REFERENCES cliente (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT ck_correo_formato CHECK (correo ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

-- Bonificaciones (Tajinaste Plus): atributo MULTIVALUADO -> tabla propia.
-- Solo deberían existir para clientes con fecha_ingreso no nula.
CREATE TABLE cliente_bonificacion (
    id_cliente    INTEGER       NOT NULL,
    bonificacion  VARCHAR(100)  NOT NULL,
    CONSTRAINT pk_cliente_bonificacion PRIMARY KEY (id_cliente, bonificacion),
    CONSTRAINT fk_cliente_bonificacion FOREIGN KEY (id_cliente)
        REFERENCES cliente (id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- PEDIDO. Contiene las claves foráneas de las dos relaciones 1:N:
--   Realiza  (cliente)  -> id_cliente
--   Gestiona (empleado) -> dni_empleado + su atributo "Cantidad"
-- El atributo DERIVADO "Precio" NO se almacena: se calcula en la vista v_pedido (más abajo).
-- Borrar un cliente borra sus pedidos (CASCADE); un empleado que gestiona pedidos no se puede borrar (RESTRICT).
CREATE TABLE pedido (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fecha                DATE     NOT NULL DEFAULT CURRENT_DATE,
    id_cliente           INTEGER  NOT NULL,
    dni_empleado         CHAR(9)  NOT NULL,
    cantidad_gestionada  INTEGER  NOT NULL,
    CONSTRAINT pk_pedido PRIMARY KEY (id),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pedido_empleado FOREIGN KEY (dni_empleado)
        REFERENCES empleado (dni) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_pedido_fecha    CHECK (fecha >= DATE '2000-01-01'),
    CONSTRAINT ck_pedido_cantidad CHECK (cantidad_gestionada > 0)
);

-- ZONA_TIENE_PRODUCTO (relación Tiene, N:M Zona-Producto): stock de un producto en una zona.
-- Clave foránea compuesta hacia la clave compuesta de Zona.
CREATE TABLE zona_tiene_producto (
    id_vivero        INTEGER      NOT NULL,
    nombre_zona      VARCHAR(60)  NOT NULL,
    codigo_producto  VARCHAR(10)  NOT NULL,
    cantidad         INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_zona_tiene_producto PRIMARY KEY (id_vivero, nombre_zona, codigo_producto),
    CONSTRAINT fk_zona_tiene_producto_zona FOREIGN KEY (id_vivero, nombre_zona)
        REFERENCES zona (id_vivero, nombre) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_zona_tiene_producto_producto FOREIGN KEY (codigo_producto)
        REFERENCES producto (codigo) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT ck_zona_tiene_producto_cantidad CHECK (cantidad >= 0)
);

-- PEDIDO_INCLUYE_PRODUCTO (relación Incluye, N:M Pedido-Producto). "cantidad" = unidades de ese producto
-- en el pedido (necesaria para calcular el precio derivado del pedido).
-- Un producto que aparece en pedidos no se puede borrar (RESTRICT).
CREATE TABLE pedido_incluye_producto (
    id_pedido        INTEGER      NOT NULL,
    codigo_producto  VARCHAR(10)  NOT NULL,
    cantidad         INTEGER      NOT NULL DEFAULT 1,
    CONSTRAINT pk_pedido_incluye_producto PRIMARY KEY (id_pedido, codigo_producto),
    CONSTRAINT fk_pedido_incluye_producto_pedido FOREIGN KEY (id_pedido)
        REFERENCES pedido (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pedido_incluye_producto_producto FOREIGN KEY (codigo_producto)
        REFERENCES producto (codigo) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_pedido_incluye_producto_cantidad CHECK (cantidad > 0)
);

-- 3. ATRIBUTO DERIVADO: Pedido.Precio = suma(cantidad x precio) de sus productos
--    Se calcula siempre al consultar, así nunca queda desactualizado.
--    (Un pedido sin líneas devuelve 0.)
CREATE VIEW v_pedido AS
SELECT p.id,
       p.fecha,
       p.id_cliente,
       p.dni_empleado,
       p.cantidad_gestionada,
       COALESCE(SUM(i.cantidad * pr.precio), 0)::NUMERIC(10,2) AS precio
FROM pedido p
LEFT JOIN pedido_incluye_producto  i  ON i.id_pedido = p.id
LEFT JOIN producto pr ON pr.codigo   = i.codigo_producto
GROUP BY p.id;

